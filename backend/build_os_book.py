# ==================== 第一章 操作系统引论 ====================
h1("第一章 操作系统引论")

h2("1.1 操作系统的基本概念")
p("操作系统（Operating System，OS）是配置在计算机硬件上的第一层软件，是对硬件系统的首次扩充。"
  "它是一组控制和管理计算机硬件与软件资源、合理组织计算机工作流程、方便用户使用的程序和数据结构的集合。"
  "操作系统在计算机系统中充当硬件与用户之间的接口，其他所有软件都依赖操作系统的支持。")
p("操作系统的主要目标包括：方便性（用户无需了解硬件细节即可使用计算机）、有效性（提高资源利用率和系统吞吐量）、"
  "可扩充性（便于功能模块的增加与修改）和开放性（遵循国际标准，便于互操作）。")
p("操作系统的作用可以从三个角度理解：一是作为用户与计算机硬件系统之间的接口，提供命令方式、系统调用方式和图形窗口方式；"
  "二是作为计算机系统资源的管理者，管理处理机、存储器、I/O 设备和文件四类资源；"
  "三是实现对计算机资源的抽象，通过多层抽象把复杂的硬件操作封装成简单易用的接口。")

h2("1.2 操作系统的发展过程")
p("人工操作阶段（无操作系统）：用户独占全机，CPU 等待手工操作，资源利用率极低，主要矛盾是人-机矛盾。"
  "脱机输入/输出技术利用外围机控制卡片和磁带，减少了 CPU 空闲时间。")
p("单道批处理系统：把一批作业以脱机方式输入到磁带上，监督程序自动依次调入内存执行，内存中始终只有一道作业。"
  "其特征是自动性、顺序性和单道性，缺点是程序发出 I/O 请求时 CPU 处于等待状态，资源利用率不高。")
p("多道批处理系统：在内存中同时存放若干道作业，当一道作业因 I/O 而暂停时，处理机转去执行另一道作业，"
  "从而使 CPU、内存和外设保持忙碌。其优点是资源利用率高、系统吞吐量大；缺点是平均周转时间长、无交互能力。"
  "多道程序设计的宏观上多道程序并行运行、微观上交替执行，需要解决处理机分配、内存分配与保护、I/O 分配和文件组织等问题。")
p("分时系统：在一台主机上连接多个终端，系统把处理机时间划分为时间片，轮流为各终端用户服务。"
  "其特征是多路性、独立性、及时性和交互性，典型实现采用时间片轮转算法。")
p("实时系统：要求系统能及时响应外部事件并在规定时间内完成处理，分为实时控制系统（如工业控制、导弹制导）"
  "和实时信息处理系统（如订票系统、情报检索）。实时系统最强调及时性和可靠性，常采用抢占式调度和冗余措施。")

h2("1.3 操作系统的基本特性与功能")
p("操作系统的四个基本特征：并发性（多个事件在同一时间间隔内发生，并行是同一时刻发生；引入进程和线程实现并发）、"
  "共享性（系统资源可供多个并发执行的进程共同使用，分为互斥共享和同时访问两种方式）、"
  "虚拟性（通过某种技术把一个物理实体变为若干个逻辑上的对应物，如虚拟处理机、虚拟内存、虚拟设备）、"
  "异步性（进程以不可预知的速度向前推进，即不确定性，但只要运行环境相同，结果应可再现）。")
p("操作系统的五大主要功能：处理机管理（进程控制、进程同步、进程通信、调度）、存储器管理（内存分配与回收、"
  "内存保护、地址映射、内存扩充）、设备管理（缓冲管理、设备分配、设备处理）、文件管理（文件存储空间管理、"
  "目录管理、文件读写与保护）以及提供用户接口（程序接口即系统调用、命令接口、图形接口）。")

# ==================== 第二章 进程管理 ====================
h1("第二章 进程的描述与控制")

h2("2.1 进程的概念与特征")
p("在多道程序环境下，程序的执行属于并发执行，具有间断性、失去封闭性和不可再现性，传统程序本身无法参与并发执行。"
  "为此引入进程：进程是进程实体的运行过程，是系统进行资源分配和调度的一个独立单位。"
  "进程实体（进程映像）由程序段、相关的数据段和进程控制块 PCB 三部分组成。")
p("进程的基本特征：动态性（进程是程序的一次执行，有生命周期，是最基本特征）、并发性（多个进程同存于内存可同时执行）、"
  "独立性（进程是资源分配和调度的独立单位）、异步性（进程按各自独立的、不可预知的速度推进）。"
  "进程与程序的区别：程序是静态的指令集合可长期保存，进程是动态的、暂时的；一个程序可对应多个进程。")

h2("2.2 进程的状态与进程控制块")
p("进程的三种基本状态：就绪状态（已分配除 CPU 外的所有资源，等待调度）、执行状态（已获得 CPU，程序正在执行）、"
  "阻塞状态（因发生某事件如 I/O 请求而暂时无法继续执行，放弃 CPU）。"
  "状态转换：就绪→执行由进程调度引起；执行→就绪由时间片用完或高优先级进程进入引起；"
  "执行→阻塞由等待某事件引起（主动行为）；阻塞→就绪由所等待事件发生引起（被动唤醒）。"
  "此外还引入创建状态和终止状态，共五种状态。")
p("进程控制块 PCB 是进程存在的唯一标志，它记录操作系统所需的、用于描述进程情况及控制进程运行所需的全部信息，"
  "包括进程标识符、处理机状态信息（通用寄存器、程序计数器、程序状态字、栈指针）、进程调度信息（状态、优先级、等待事件）"
  "和进程控制信息（资源清单、同步通信信息、链接指针）。PCB 的组织方式有线性方式、链接方式和索引方式。")

h2("2.3 进程控制")
p("进程控制由内核原语实现，原语是执行过程中不可中断的程序段，采用关中断指令保证原子性。"
  "创建原语：申请空白 PCB、为新进程分配资源、初始化 PCB、将进程插入就绪队列。"
  "引起创建的事件有用户登录、作业调度、提供服务、应用请求。")
p("终止原语：根据标识符找到 PCB，若进程正在执行则终止并调度新进程，终止其子孙进程，归还资源，从队列中移除 PCB。"
  "阻塞原语是进程主动调用：保存现场、状态改为阻塞、插入对应事件的阻塞队列、转调度程序；"
  "唤醒原语：把阻塞进程从等待队列移出、状态改为就绪、插入就绪队列。")

h2("2.4 进程同步与互斥")
p("进程同步的主要任务是协调多个相关进程的执行次序。间接相互制约关系源于资源共享（互斥），"
  "直接相互制约关系源于进程合作（同步）。临界资源是一段时间内只允许一个进程访问的资源，如打印机、共享变量；"
  "每个进程中访问临界资源的代码称为临界区。")
p("同步机制应遵循四条准则：空闲让进（无进程在临界区时可允许一个进入）、忙则等待（已有进程在临界区时其他必须等待）、"
  "有限等待（等待时间应有限，避免死等）、让权等待（不能进入临界区时应释放处理机，避免忙等）。")
p("信号量机制：整型信号量定义整型量 S，通过两个标准原子操作 wait(S)（P 操作，S=S-1，S<0 则循环等待）"
  "和 signal(S)（V 操作，S=S+1，S≤0 则唤醒一个等待进程）访问。记录型信号量增加阻塞队列，"
  "S.value 表示资源数目，P 操作资源不足时自我阻塞，实现让权等待。AND 型信号量同时申请多个资源。")
p("利用信号量实现互斥：设互斥信号量 mutex 初值为 1，临界区前 P(mutex)、临界区后 V(mutex)。"
  "实现前趋关系：为每对前趋关系设置初值为 0 的信号量，前序进程执行后 V，后继进程执行前 P。")

h2("2.5 经典进程同步问题")
p("生产者-消费者问题：一组生产者向有 n 个缓冲区的环形缓冲池放产品，消费者从中取产品。"
  "设互斥信号量 mutex=1，空缓冲区信号量 empty=n，满缓冲区信号量 full=0。"
  "生产者先 P(empty) 再 P(mutex)，放入产品后 V(mutex)、V(full)；消费者先 P(full) 再 P(mutex)，取走后 V(mutex)、V(empty)。"
  "注意 P 操作顺序不能颠倒，否则可能死锁；V 操作顺序无关紧要。")
p("读者-写者问题：多个读者可同时读，写者必须独占访问，任一写者在写时其他读者和写者均不能访问。"
  "设 readcount 记录读者数及互斥它的 rmutex=1、读写互斥 rwmutex=1。第一读者 P(rwmutex)，最后一读者 V(rwmutex)。"
  "该方案读者优先，可能使写者饥饿；可通过增加公平信号量改进。")
p("哲学家进餐问题：五位哲学家交替思考和进餐，左右各一支筷子共五支。若同时拿起左筷会死锁。"
  "解决方法：至多四位哲学家同时拿左筷；仅当左右筷子都可用时才拿起（AND 信号量一次性申请）；奇数号先拿左、偶数号先拿右。")

h2("2.6 进程通信与线程")
p("进程通信指进程间的信息交换，低级通信即信号量只传递少量控制信息，高级通信能高效传递大量数据，主要有："
  "共享存储器系统（通过共享数据结构或共享存储区通信）、消息传递系统（以格式化消息为单位，分直接通信和信箱通信）、"
  "管道通信（连接读进程和写进程的共享文件，以字符流方式传送，需互斥、同步和确定对方存在）。")
p("线程是比进程更小的能独立运行的基本单位，是处理机调度和分派的基本单位。引入线程后，进程只作为资源拥有的单位，"
  "线程作为调度和分派的单位。线程切换只需保存少量寄存器和栈，切换开销小；同进程内线程共享内存和文件，通信无需内核。"
  "线程分为用户级线程（在用户空间通过线程库管理，内核不知晓）和内核级线程（由内核完成创建、调度和管理）。")

# ==================== 第三章 处理机调度与死锁 ====================
h1("第三章 处理机调度与死锁")

h2("3.1 处理机调度的层次")
p("高级调度（作业调度/长程调度）：从外存后备队列中选择作业调入内存、创建进程并插入就绪队列，"
  "决定哪些作业能进入内存，多道批处理系统必须配置，分时和实时系统通常不设置。"
  "低级调度（进程调度/短程调度）：从就绪队列中选择进程把处理机分配给它，是最基本的调度，所有 OS 都必须配置。"
  "中级调度（内存调度）：为提高内存利用率和系统吞吐量，把暂时不能运行的进程调至外存挂起，条件具备再调回内存。")
p("进程调度方式：非抢占方式（一旦把处理机分配给进程便一直运行直到完成或阻塞，实现简单、适合批处理）；"
  "抢占方式（可按优先权、短作业优先或时间片原则暂停正在执行的进程，适合分时实时系统，开销较大但更公平及时）。")

h2("3.2 调度算法")
p("先来先服务 FCFS：按到达先后次序调度，可用于作业和进程调度，非抢占。优点是简单；缺点是对短作业不利，"
  "带权周转时间可能很大，有利于 CPU 繁忙型作业、不利于 I/O 繁忙型作业。")
p("短作业优先 SJF：选择估计运行时间最短的作业/进程，可有效降低平均等待时间、提高吞吐量；"
  "缺点是对长作业不利、可能造成长作业饥饿，估计时间可能不准确，未考虑紧迫程度。")
p("优先级调度算法：按优先级高低调度，分为抢占式和非抢占式。优先级可分为静态优先级（创建时确定、不变）"
  "和动态优先级（运行中调整，如随等待时间增长而提高）。常采用让高响应比、老化技术防止低优先级进程饥饿。")
p("高响应比优先调度：每次计算各作业的动态优先权，响应比 Rp =（等待时间+要求服务时间）/ 要求服务时间。"
  "等待越久优先级越高，兼顾了长作业和短作业，但每次调度前都要计算，增加系统开销。")
p("时间片轮转 RR：就绪进程按 FCFS 排队，每次把一个时间片（如 10~100ms）分配给队首进程，时间片用完即剥夺并排到队尾。"
  "时间片大小影响响应时间和切换开销：过大退化为 FCFS，过小切换频繁。")
p("多级反馈队列调度：设置多个由高到低优先级的就绪队列，优先级越高时间片越短；新进程先进入最高优先级队列，"
  "用完时间片则降到下一级；仅当高优先级队列为空时才调度低队列。该算法兼顾各类作业，是公认较好的进程调度算法。")

h2("3.3 死锁概述")
p("死锁是指多个进程在运行过程中因争夺资源而造成的一种僵局，若无外力作用，这些进程都将永远不能再向前推进。"
  "产生死锁的四个必要条件（必须同时满足）：互斥条件（资源一段时间内只由一个进程占用）、"
  "请求和保持条件（已保持至少一个资源又提出新资源请求，且对已有资源保持不放）、"
  "不剥夺条件（资源只能由持有者主动释放，不能强行剥夺）、循环等待条件（存在进程-资源的循环等待链）。")
p("处理死锁的四种方法：预防死锁（破坏四个必要条件之一或几个）、避免死锁（在资源分配中防止系统进入不安全状态，如银行家算法）、"
  "检测死锁（允许发生，通过资源分配图及时发现并解除）、解除死锁（剥夺资源或撤销进程）。")

h2("3.4 死锁预防与银行家算法")
p("破坏请求和保持条件：进程运行前一次性申请全部所需资源，或在没有占有资源时才能申请；资源利用率低。"
  "破坏不剥夺条件：请求新资源不能满足时必须释放已占资源；实现复杂、代价大，适合 CPU 等可抢占资源。"
  "破坏循环等待条件：对所有资源线性排序，进程按序号递增顺序申请资源；序号相对稳定但限制了设备增删。")
p("安全状态：系统能按某种顺序为每个进程分配其所需资源，使每个进程都能顺利完成，该序列称为安全序列。"
  "安全状态一定不会死锁，不安全状态不一定死锁但存在死锁风险；银行家算法保证系统始终处于安全状态。")
p("银行家算法：进程提出资源请求时，先检查请求是否超过其声明的最大需求、是否超过系统可用资源；"
  "然后试探性分配，执行安全性算法：若能找到安全序列则正式分配，否则进程等待。"
  "安全性算法通过工作向量 Work 和完成标志 Finish，反复寻找可满足剩余需求的进程并回收其资源。")
p("死锁检测：利用资源分配图，找出既不阻塞又不是孤点的进程，消去它的分配边和请求边，反复化简；"
  "若不能完全化简则存在死锁。解除方法：剥夺资源（挂起某些进程）、撤销进程（按代价最小原则终止死锁进程）、回退到检查点。")

# ==================== 第四章 存储器管理 ====================
h1("第四章 存储器管理")

h2("4.1 存储器管理基础")
p("存储器层次：CPU 寄存器、高速缓存、主存储器（内存）、磁盘缓存和固定磁盘，访问速度递减、容量递增。"
  "内存管理的主要功能：内存分配与回收、内存保护（确保每道程序只在自己的内存空间运行）、"
  "地址映射（把逻辑地址转换为物理地址）和内存扩充（通过虚拟存储技术从逻辑上扩充容量）。")
p("程序的装入方式：绝对装入（编译时确定物理地址，适合单道系统）、可重定位装入（装入时把逻辑地址转换为物理地址，"
  "即静态重定位，地址变换在装入时一次完成）、动态运行时装入（装入后地址仍为相对地址，执行到指令时由重定位寄存器转换，"
  "即动态重定位，允许程序在内存中移动）。链接方式分为静态链接、装入时动态链接和运行时动态链接。")

h2("4.2 连续分配方式")
p("单一连续分配：内存分为系统区和用户区，用户区仅一道作业独占，简单但利用率低。")
p("固定分区分配：把用户空间划分为若干固定大小的分区，每个分区装一道作业，可按分区大小相等或不等划分；"
  "通过分区说明表管理，会产生内部碎片（已分配分区内未使用的部分）。")
p("动态分区分配（可变分区）：不预先划分，作业装入时按需要动态建立分区。常用数据结构为空闲分区表/链；"
  "分配算法：首次适应 FF（从链首找第一个够大的分区，低址部分易形成碎片）、循环首次适应 NF（从上次位置继续找）、"
  "最佳适应 BF（选择最小的够大分区，留下许多难以利用的小碎片）、最坏适应 WF（选最大分区分割）。"
  "回收时需考虑相邻空闲分区合并（上邻、下邻、上下邻）。动态分区产生外部碎片，可通过紧凑（拼接）技术集中空闲区。")
p("可重定位分区分配：通过动态重定位，把所有作业移动使碎片集中为一个大空闲区（紧凑），紧凑需要重定位寄存器支持。")

h2("4.3 分页与分段存储管理")
p("基本分页存储管理：把进程的逻辑地址空间分成大小相等的页面（页，典型 4KB），内存分成同样大小的物理块（帧）。"
  "逻辑地址由页号 P 和页内偏移 W 组成，通过页表把页号映射为物理块号，物理地址 = 块号×块长+偏移。"
  "分页消除了外部碎片，仅有少量内部碎片；地址变换借助页表寄存器和高速缓冲（联想存储器 TLB，快表）加速。")
p("二级分页与多级页表：现代系统逻辑空间巨大，采用二级（外层页目录+页表）甚至多级页表，只为实际使用的页面建立页表。")
p("基本分段存储管理：按程序的逻辑结构（如主程序段、子程序段、数据段、栈段）划分，每段有段名（段号）和段长。"
  "逻辑地址由段号和段内地址组成，段表记录每段在内存的起始地址和长度，地址变换时要检查段长防止越界。"
  "分段便于编程、共享和保护、动态增长与动态链接；分段产生外部碎片。")
p("分页与分段的主要区别：页是信息的物理单位，大小固定由系统决定，出于系统管理需要；段是信息的逻辑单位，"
  "大小不固定由用户程序决定，出于满足用户需要；分页作业地址空间一维，分段二维（需给出段名和段内地址）。"
  "段页式管理结合两者：先分段，段内再分页。")

h2("4.4 虚拟存储器与请求分页")
p("基于局部性原理（时间局限性和空间局限性），程序装入时不必全部装入内存，只装入部分页面即可运行，"
  "访问到不在内存的页面时再请求调入，必要时置换，这样的系统称为虚拟存储器。其特征是离散性、多次性、对换性和虚拟性，"
  "最大容量受 CPU 地址位数限制，实际容量受内存和外存容量共同限制。")
p("请求分页机制：页表项增加状态位（存在位）、访问字段、修改位和外存地址。缺页时产生缺页中断（属于内故障，"
  "一条指令执行期间可能产生多次），由中断处理程序从外存调入页面；内存已满则执行页面置换。")
p("最佳置换算法 OPT：选择以后永不使用或最长时间内不再被访问的页面淘汰，缺页率最低但无法实现，常作为评价标准。")
p("先进先出置换 FIFO：淘汰最先进入内存的页面，实现简单但可能淘汰常用页面；会出现 Belady 异常（分配物理块增多，缺页次数反而增多）。")
p("最近最久未使用 LRU：淘汰最近最长时间未访问的页面，利用访问时间字段或栈实现，性能接近 OPT，开销较大；"
  "LRU 属于堆栈型算法，不会出现 Belady 异常。简单近似实现有时钟算法 Clock（最近未用算法 NRU，利用访问位循环扫描）。")
p("抖动（颠簸）：刚被换出的页面很快又要访问，频繁的页面置换使大部分时间花在调页上。"
  "产生原因是同时运行进程过多、分配物理块不足。预防方法：采用工作集模型（根据近期访问页面集合确定应分配块数）、"
  "调整多道程序度、挂起部分进程。")

# ==================== 第五章 设备管理 ====================
h1("第五章 设备管理")

h2("5.1 I/O 系统与控制方式")
p("I/O 设备按使用特性分为存储设备（磁盘、磁带）和 I/O 设备（键盘、显示器、打印机）；"
  "按传输速率分为低速、中速、高速设备；按共享属性分为独占设备、共享设备和虚拟设备。"
  "设备控制器是 CPU 与设备之间的接口，包含控制寄存器、数据寄存器和状态寄存器，通过中断与 CPU 通信。")
p("I/O 控制方式的发展：程序直接控制方式（轮询，CPU 与设备串行工作，利用率低）；"
  "中断驱动方式（设备完成后发中断通知 CPU，CPU 与设备并行，但以字为单位，中断次数多）；"
  "DMA 方式（直接存储器存取，以数据块为单位，数据直接在设备与内存间传输，仅传送开始和结束时需 CPU 干预）；"
  "通道方式（通道是专用处理机，执行通道程序控制一组设备完成 I/O，进一步减少 CPU 干预，分字节多路、数组选择、数组多路通道）。")

h2("5.2 缓冲管理")
p("引入缓冲的目的：缓和 CPU 与 I/O 设备速度不匹配的矛盾；减少对 CPU 的中断频率，放宽中断响应时间限制；"
  "提高 CPU 与设备、设备与设备之间的并行性。缓冲类型：单缓冲（一块缓冲区，处理与输入交替）、"
  "双缓冲（两块，可双向并行，提高效率）、循环缓冲（多个缓冲区组成环形链）和缓冲池（多个可供多个进程共享的缓冲区，"
  "含空缓冲队列、输入队列、输出队列，工作方式有收容输入、提取输入、收容输出、提取输出）。")

h2("5.3 设备分配与 SPOOLing 技术")
p("设备分配依据的数据结构：设备控制表 DCT、控制器控制表 COCT、通道控制表 CHCT、系统设备表 SDT。"
  "分配策略常采用先来先服务和优先级；独占设备可能引起死锁，共享设备不需预先分配。"
  "逻辑设备名到物理设备的映射通过逻辑设备表 LUT 实现设备独立性（应用程序使用逻辑设备名，便于重定向和统一接口）。")
p("SPOOLing（外部设备同时联机操作，假脱机技术）：在磁盘上开辟输入井和输出井，在内存开辟输入缓冲区和输出缓冲区，"
  "由输入进程和输出进程（守护进程）模拟脱机 I/O。以打印机为例：用户打印实际是把数据送入输出井排队，"
  "打印守护进程依次打印，把独占打印机改造为可共享的虚拟打印机，实现虚拟设备功能，提高了 I/O 速度和设备利用率。")

h2("5.4 磁盘存储器管理")
p("磁盘访问时间 = 寻道时间（磁头移动到指定磁道，最主要且可优化）+ 旋转延迟时间（等待扇区转到磁头下，平均约半周）"
  "+ 传输时间。磁盘调度算法的目标是减少平均寻道时间。")
p("先来先服务 FCFS：按请求先后顺序，公平但寻道距离大。最短寻道时间优先 SSTF：选择距当前磁头最近的请求，"
  "性能较好但可能使远离磁头的请求饥饿。扫描算法 SCAN（电梯算法）：磁头沿一个方向移动并处理沿途请求，到尽头再折返，"
  "兼顾两端。循环扫描 C-SCAN：到达尽头后直接返回起点再沿同一方向扫描，各扇区等待更均匀。")
p("磁盘高速缓存：在内存中为磁盘块设置缓存，命中则直接访问；可采用 LRU 等置换策略，还可通过提前读、延迟写、优化物理块分布提高性能。")

# ==================== 第六章 文件系统 ====================
h1("第六章 文件管理")

h2("6.1 文件与文件系统")
p("文件是具有符号名的、在逻辑上具有完整意义的一组相关信息项的有序集合，由文件体（内容）和文件说明（属性）组成。"
  "文件按性质和用途分为系统文件、用户文件、库文件；按逻辑结构分为有结构文件（记录式文件）和无结构文件（流式文件）；"
  "按操作保护分为只读、读写、只执行文件。文件系统是操作系统中负责管理文件的机构，提供按名存取、共享与保护等功能。")
p("文件的逻辑结构（从用户角度）：无结构的字符流式文件（如源程序、文本）；有结构的记录式文件又分为顺序文件"
  "（记录按顺序排列，可顺序存取或随机存取）、索引文件（为变长记录建立索引表）和索引顺序文件（记录分组，组内顺序、组间索引）。")

h2("6.2 文件的物理结构")
p("连续分配：每个文件占用一组连续的磁盘块，只需起始块号和长度。优点是顺序访问快、管理简单；"
  "缺点是会产生外部碎片，文件难以动态增长。")
p("链接分配：文件信息分散在不连续的块中，每块设置指向下一块的指针。隐式链接只适合顺序访问、可靠性差；"
  "显式链接把所有链接指针集中存放在文件分配表 FAT 中，查找较快，FAT 需常驻内存。")
p("索引分配：为每个文件建立索引块（索引节点 inode），记录文件各逻辑块对应的物理块号，支持高效随机访问；"
  "大文件可采用多级索引（一级、二级、三级）或混合索引（如直接地址、一次间接、二次间接、三次间接地址相结合）。")

h2("6.3 目录管理")
p("文件控制块 FCB 是用于描述和控制文件的数据结构，包含文件名、物理位置、逻辑结构、存取控制信息和时间信息；"
  "文件目录是 FCB 的有序集合。目录结构的发展：单级目录（简单但查找慢、重名问题）、两级目录（主文件目录+用户目录，解决重名）、"
  "多级树形目录（用路径名唯一标识文件，分为绝对路径和相对路径，当前目录可缩短检索路径）、无环图目录（允许文件共享，用链接计数管理）。")

h2("6.4 文件存储空间管理与保护")
p("空闲空间管理方法：空闲表法（连续分配时使用）、空闲链表法（空闲盘块链、空闲盘区链）、"
  "位示图法（用二进制位标记块是否空闲，查找和分配回收方便）、成组链接法（把空闲块分组并链接，UNIX 常用，兼顾表和链的优点）。")
p("文件共享：基于索引节点的共享（不同目录项指向同一 inode，设置链接计数）和利用符号链接（建立 LINK 文件记录路径，"
  "可跨文件系统但需读路径、开销较大）。文件保护通过存取控制矩阵、存取控制表、用户权限表和口令、密码等方式实现；"
  "文件系统可靠性通过磁盘坏块管理、备份（全量转储、增量转储）和一致性检查保证。")

